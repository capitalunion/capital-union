let currentLang = localStorage.getItem('cu_lang') || 'ru';
let darkMode = localStorage.getItem('cu_dark') === 'true';

function t(key) {
  return (translations[currentLang] && translations[currentLang][key])
      || (translations['ru'] && translations['ru'][key])
      || key;
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const attr = el.getAttribute('data-i18n-attr');
    if (attr) el.setAttribute(attr, t(key));
    else el.textContent = t(key);
  });
  document.querySelectorAll('.lang-btn-kk').forEach(el => {
    el.classList.toggle('active-lang', currentLang === 'kk');
  });
  document.querySelectorAll('.lang-btn-ru').forEach(el => {
    el.classList.toggle('active-lang', currentLang === 'ru');
  });
}

function switchLang(lang) {
  currentLang = lang;
  localStorage.setItem('cu_lang', lang);
  applyTranslations();
}

function applyTheme() {
  document.body.classList.toggle('dark-theme', darkMode);
  document.querySelectorAll('.theme-icon').forEach(el => {
    el.textContent = darkMode ? '☀️' : '🌙';
  });
}

function toggleTheme() {
  darkMode = !darkMode;
  localStorage.setItem('cu_dark', darkMode);
  applyTheme();
}

function initCursor() {
  const dot = document.querySelector('.cursor-dot');
  const ring = document.querySelector('.cursor-ring');
  if (!dot || !ring) return;
  let mx = 0, my = 0, rx = 0, ry = 0;
  document.addEventListener('mousemove', e => { mx = e.clientX; my = e.clientY; });
  function animateCursor() {
    rx += (mx - rx) * 0.15;
    ry += (my - ry) * 0.15;
    dot.style.left = mx + 'px';
    dot.style.top = my + 'px';
    ring.style.left = rx + 'px';
    ring.style.top = ry + 'px';
    requestAnimationFrame(animateCursor);
  }
  animateCursor();
  document.querySelectorAll('a, button, .cu-card, .project-card, input, textarea, select').forEach(el => {
    el.addEventListener('mouseenter', () => {
      ring.style.width = '50px';
      ring.style.height = '50px';
    });
    el.addEventListener('mouseleave', () => {
      ring.style.width = '30px';
      ring.style.height = '30px';
    });
  });
}

function initScrollTop() {
  const btn = document.getElementById('scrollTopBtn');
  if (!btn) return;
  window.addEventListener('scroll', () => {
    btn.classList.toggle('visible', window.scrollY > 300);
  });
  btn.addEventListener('click', () => {
    $('html, body').animate({ scrollTop: 0 }, 500);
  });
}

function initReveal() {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(e => {
      if (e.isIntersecting) $(e.target).addClass('visible');
    });
  }, { threshold: 0.12 });
  document.querySelectorAll('.reveal, .reveal-left, .reveal-right').forEach(el => observer.observe(el));
}

function animateCounters() {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        const el = entry.target;
        const target = parseFloat(el.getAttribute('data-target'));
        let start = 0;
        const duration = 1800;
        const step = (timestamp) => {
          if (!start) start = timestamp;
          const progress = Math.min((timestamp - start) / duration, 1);
          const eased = 1 - Math.pow(1 - progress, 3);
          el.textContent = Math.floor(eased * target).toLocaleString();
          if (progress < 1) requestAnimationFrame(step);
        };
        requestAnimationFrame(step);
        observer.unobserve(el);
      }
    });
  }, { threshold: 0.5 });
  document.querySelectorAll('.counter-num').forEach(el => observer.observe(el));
}

function showToast(msg) {
  let toast = document.querySelector('.cu-toast');
  if (!toast) {
    toast = document.createElement('div');
    toast.className = 'cu-toast';
    document.body.appendChild(toast);
  }
  toast.textContent = msg;
  $(toast).addClass('show');
  setTimeout(() => $(toast).removeClass('show'), 3500);
}

function initForm() {
  const form = document.getElementById('contactForm');
  if (!form) return;
  form.addEventListener('submit', function(e) {
    e.preventDefault();
    const btn = form.querySelector('[type=submit]');
    const origText = btn.textContent;
    btn.disabled = true;
    btn.textContent = '⏳';
    setTimeout(() => {
      btn.disabled = false;
      btn.textContent = origText;
      form.reset();
      showToast(t('form_success'));
    }, 1200);
  });
}

function setActiveNav() {
  const page = location.pathname.split('/').pop() || 'index.html';
  document.querySelectorAll('.nav-link').forEach(link => {
    const href = link.getAttribute('href') || '';
    link.classList.toggle('active', href === page || (page === '' && href === 'index.html'));
  });
}

$(document).ready(function () {
  $('body').hide().fadeIn(500);

  $(document).on('click', 'a[href^="#"]', function (e) {
    const target = $(this.getAttribute('href'));
    if (target.length) {
      e.preventDefault();
      $('html, body').animate({ scrollTop: target.offset().top - 72 }, 600);
    }
  });

  $(window).on('scroll', function () {
    if ($(this).scrollTop() > 60) {
      $('nav.navbar').css('padding', '0');
    }
  });

  $(document).on('click', '.lang-btn-ru', () => switchLang('ru'));
  $(document).on('click', '.lang-btn-kk', () => switchLang('kk'));
  $(document).on('click', '.theme-btn', () => toggleTheme());

  $(document).on('click', '.filter-btn', function () {
    $('.filter-btn').removeClass('btn-cu-primary').addClass('btn-outline-secondary');
    $(this).removeClass('btn-outline-secondary').addClass('btn-cu-primary');
    const filter = $(this).data('filter');
    if (filter === 'all') {
      $('.project-item').fadeIn(300);
    } else {
      $('.project-item').fadeOut(200);
      $('.project-item[data-status="' + filter + '"]').fadeIn(300);
    }
  });

  applyTheme();
  applyTranslations();
  initCursor();
  initScrollTop();
  initReveal();
  animateCounters();
  initForm();
  setActiveNav();
});